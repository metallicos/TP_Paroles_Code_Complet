                "# Classe du modèle Neural Network simple (inspiré du cours)\n",
                "class LyricsGenerationModel:\n",
                "    \"\"\"\n",
                "    Modèle simple de génération de paroles.\n",
                "    Architecture:\n",
                "    - Embedding d'entrée: convertit les indices de mots en vecteurs\n",
                "    - Embedding de condition: convertit le genre en vecteur\n",
                "    - Couche cachée: applique une transformation\n",
                "    - Sortie: logits pour chaque mot du vocabulaire\n",
                "    \"\"\"\n",
                "    \n",
                "    def __init__(self, vocab_size, embedding_dim=16, hidden_dim=32, num_genres=5):\n",
                "        self.vocab_size = vocab_size\n",
                "        self.embedding_dim = embedding_dim\n",
                "        self.hidden_dim = hidden_dim\n",
                "        self.num_genres = num_genres\n",
                "        \n",
                "        # Initialiser les poids aléatoirement\n",
                "        np.random.seed(42)\n",
                "        \n",
                "        # Embedding pour les mots (vocab_size x embedding_dim)\n",
                "        self.word_embedding = np.random.randn(vocab_size, embedding_dim) * 0.01\n",
                "        \n",
                "        # Embedding pour les genres (num_genres x embedding_dim)\n",
                "        self.genre_embedding = np.random.randn(num_genres, embedding_dim) * 0.01\n",
                "        \n",
                "        # Poids de la couche cachée: (SEQ_LEN * embedding_dim + embedding_dim) -> hidden_dim\n",
                "        self.W1 = np.random.randn(SEQ_LEN * embedding_dim + embedding_dim, hidden_dim) * 0.01\n",
                "        self.b1 = np.zeros((1, hidden_dim))\n",
                "        \n",
                "        # Poids de sortie: hidden_dim -> vocab_size\n",
                "        self.W2 = np.random.randn(hidden_dim, vocab_size) * 0.01\n",
                "        self.b2 = np.zeros((1, vocab_size))\n",
                "        \n",
                "        self.loss_history = []\n",
                "        self.val_loss_history = []\n",
                "    \n",
                "    def forward(self, X_batch, genres_batch):\n",
                "        \"\"\"\n",
                "        Forward pass du modèle.\n",
                "        X_batch: (batch_size, SEQ_LEN) - indices des mots\n",
                "        genres_batch: (batch_size,) - indices des genres\n",
                "        \"\"\"\n",
                "        batch_size = X_batch.shape[0]\n",
                "        \n",
                "        # Embedding des mots\n",
                "        word_embeds = self.word_embedding[X_batch]  # (batch_size, SEQ_LEN, embedding_dim)\n",
                "        word_embeds_flat = word_embeds.reshape(batch_size, -1)  # Aplatir\n",
                "        \n",
                "        # Embedding du genre\n",
                "        genre_embeds = self.genre_embedding[genres_batch]  # (batch_size, embedding_dim)\n",
                "        \n",
                "        # Concaténer les embeddings\n",
                "        combined = np.concatenate([word_embeds_flat, genre_embeds], axis=1)  # (batch_size, SEQ_LEN*embedding_dim + embedding_dim)\n",
                "        \n",
                "        # Couche cachée avec activation ReLU\n",
                "        z1 = np.dot(combined, self.W1) + self.b1\n",
                "        a1 = np.maximum(z1, 0)  # ReLU\n",
                "        \n",
                "        # Couche de sortie (logits)\n",
                "        z2 = np.dot(a1, self.W2) + self.b2\n",
                "        \n",
                "        return z2, a1, combined\n",
                "    \n",
                "    def compute_loss(self, logits, y_batch):\n",
                "        \"\"\"\n",
                "        Calcul de la perte (cross-entropy).\n",
                "        Cross-entropy habituelle du cours: J = -(1/m) * sum(y * log(p))\n",
                "        \"\"\"\n",
                "        batch_size = logits.shape[0]\n",
                "        \n",
                "        # Softmax pour obtenir les probabilités\n",
                "        exp_logits = np.exp(logits - np.max(logits, axis=1, keepdims=True))\n",
                "        probs = exp_logits / np.sum(exp_logits, axis=1, keepdims=True)\n",
                "        \n",
                "        # Cross-entropy loss\n",
                "        correct_log_probs = -np.log(probs[np.arange(batch_size), y_batch])\n",
                "        loss = np.mean(correct_log_probs)\n",
                "        \n",
                "        return loss, probs\n",
                "    \n",
                "    def backward(self, X_batch, genres_batch, y_batch, logits, a1, combined, probs, learning_rate=0.01):\n",
                "        \"\"\"\n",
                "        Backward pass (gradient descent comme dans le cours).\n",
                "        \"\"\"\n",
                "        batch_size = X_batch.shape[0]\n",
                "        \n",
                "        # Gradient de la perte par rapport aux logits\n",
                "        d_logits = probs.copy()\n",
                "        d_logits[np.arange(batch_size), y_batch] -= 1\n",
                "        d_logits /= batch_size\n",
                "        \n",
                "        # Gradient W2 et b2\n",
                "        dW2 = np.dot(a1.T, d_logits)\n",
                "        db2 = np.sum(d_logits, axis=0, keepdims=True)\n",
                "        \n",
                "        # Gradient d_a1\n",
                "        d_a1 = np.dot(d_logits, self.W2.T)\n",
                "        \n",
                "        # Appliquer la dérivée de ReLU\n",
                "        d_z1 = d_a1 * (a1 > 0)\n",
                "        \n",
                "        # Gradient W1 et b1\n",
                "        dW1 = np.dot(combined.T, d_z1)\n",
                "        db1 = np.sum(d_z1, axis=0, keepdims=True)\n",
                "        \n",
                "        # Mise à jour des poids (descente de gradient)\n",
                "        self.W2 -= learning_rate * dW2\n",
                "        self.b2 -= learning_rate * db2\n",
                "        self.W1 -= learning_rate * dW1\n",
                "        self.b1 -= learning_rate * db1\n",
                "\n",
                "print('✓ Modèle défini avec succès!')"
