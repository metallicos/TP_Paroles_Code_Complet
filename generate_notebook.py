                "def filter_lyrics(lyrics, min_length=20):\n",
                "    \"\"\"\n",
                "    Post-traitement des paroles générées:\n",
                "    - Supprimer les tokens spéciaux\n",
                "    - Limiter les répétitions\n",
                "    - Vérifier la longueur minimale\n",
