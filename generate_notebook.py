                "    \n",
                "    # Vérifier la longueur\n",
                "    if len(filtered_words) < min_length:\n",
                "        return None\n",
                "    \n",
                "    return ' '.join(filtered_words)\n",
                "\n",
                "print('✓ Fonction de filtrage définie!')"
